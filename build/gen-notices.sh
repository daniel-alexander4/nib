#!/usr/bin/env bash
# Regenerate THIRD-PARTY-NOTICES.md — the attribution file Nib must ship to
# satisfy the BSD/MIT/Apache-2.0 notice-preservation terms of its dependencies
# (all AGPLv3-compatible; see the file's preamble). Run this whenever go.mod or
# the vendored pdf.js changes, and commit the result alongside.
#
# It attributes exactly the third-party code that ends up in a shipped Nib:
#   - the Go modules actually linked into ./cmd/nib (not the full module graph),
#   - the vendored pdf.js engine under web/,
#   - the Go standard library / toolchain.
#
# An optional first argument names where to write the result (default
# THIRD-PARTY-NOTICES.md); the freshness-guard test passes a temp path so it can
# regenerate and diff without touching the committed file.
set -euo pipefail
cd "$(dirname "$0")/.."

# ── The Exhibit B refusal, and the door it now has (/pending 518) ─────────────
#
# The note at the end of this file rests its AGPLv3 compatibility on MPL 2.0 §3.3, and §3.3 is
# available only while no covered SOURCE file carries the Exhibit B "Incompatible With Secondary
# Licenses" notice. A dependency that adds one makes that paragraph false, so the generate stops
# rather than emitting a licence claim nobody checked.
#
# It sat inline in the module walk, where the only way to reach it was to actually depend on such
# a module — **a refusal on a distribution-facing legal document that nothing had ever run**. It is
# a function now, with a probe entry point beside it, so `notices_test.go` can drive the real
# branch on fixture directories instead of reimplementing the predicate and grading its own copy.
# ADR-009: one door, and the guard asserts the door rather than a second implementation of it.
#
# `--include='*.go'` is load-bearing and is what the probe's third case exists to hold: the MPL
# text QUOTES Exhibit B, so every LICENSE file of every MPL module matches. Searching them would
# refuse all four of the modules Nib already ships.
refuse_if_exhibit_b() { # module dir
  grep -rlq --include='*.go' 'Incompatible With Secondary Licenses' "$2" || return 0
  echo "gen-notices: $1 carries the MPL-2.0 Exhibit B notice in a source file; the" >&2
  echo "             note's §3.3 paragraph would be false — rewrite it before regenerating" >&2
  exit 1
}

# The probe: runs the refusal above and NOTHING else, so a test can see both of its answers.
# Deliberately not a flag that changes how a generate behaves — it replaces the generate.
if [ "${1:-}" = "--exhibit-b-probe" ]; then
  refuse_if_exhibit_b "${2:-probe}" "${3:?--exhibit-b-probe needs a directory}"
  echo "gen-notices: ${2:-probe} carries no Exhibit B notice in any Go source file"
  exit 0
fi

OUT="${1:-THIRD-PARTY-NOTICES.md}"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

emit() { printf '%s\n' "$1" >>"$tmp"; }

emit "# Third-Party Notices"
emit ""
# The preamble names NO license class, and that is deliberate rather than vague.
#
# It used to say "Each is under a permissive license (BSD, MIT, or Apache-2.0)", which was
# false of the set it introduces and had been for as long as `github.com/anacrolix/dht/v2`
# has been a dependency: that module is MPL-2.0, compatible through MPL 2.0 §3.3 rather
# than through being permissive, and the file's own note says so — 3,100 lines below the
# preamble a reader takes as the summary. The vendored web assets add SIL OFL and ISC,
# neither of them in the three named either.
#
# An enumeration in prose is the construction that went stale, so it is not replaced with a
# longer one. The claim made here is the one that stays true as dependencies change —
# compatible with the AGPLv3, texts reproduced per component — and anything resting on a
# non-permissive license is explained in its own note at the end of the file.
emit "Nib is licensed under the GNU Affero General Public License v3.0 (see \`LICENSE\`)."
emit "It also incorporates the third-party software listed below."
emit ""
emit "Each component is under a license compatible with the AGPLv3, and each such license"
emit "requires that its copyright and license notice be preserved in redistributions — that"
emit "is the purpose of this file. **They are not all of one class.** The full text of each"
emit "license is reproduced in that component's own section below, and where compatibility"
emit "rests on something other than the license being permissive, a note at the end of this"
emit "file explains it."
emit ""
emit "This file is generated by \`build/gen-notices.sh\`; do not edit by hand."
emit ""
emit "---"
emit ""

# --- Go modules linked into the binary -------------------------------------
mods="$(go list -deps -f '{{with .Module}}{{.Path}}{{end}}' ./cmd/nib | grep -v '^$' | sort -u | grep -v '^nib$')"

# The MPL-2.0 modules, collected FROM THE WALK rather than named by hand (/pending 505).
#
# The note at the end of this file used to name the one MPL module it knew about and say it was
# "reached only from tests" — true when written, false from the release that linked the DHT into
# `./cmd/nib`, and false about the count too: the walk linked four MPL-2.0 modules
# (`anacrolix/dht/v2`, `anacrolix/torrent`, `anacrolix/generics`, `anacrolix/log`) while the
# note named one. A licence file on a distributed binary cannot carry an enumeration nobody
# reconciles, so the list is the walk's own. `TestEveryMPLModuleIsNamedInTheNote` reads it back.
mpl_mods=()

while IFS= read -r mod; do
  read -r ver dir < <(go list -m -f '{{.Version}} {{.Dir}}' "$mod")
  emit "## ${mod} ${ver}"
  emit ""
  found=0
  for name in LICENSE LICENSE.txt LICENSE.md COPYING COPYING.txt; do
    if [ -f "$dir/$name" ]; then
      emit '```'
      cat "$dir/$name" >>"$tmp"
      emit '```'
      found=1
      if grep -q 'Mozilla Public License' "$dir/$name"; then
        mpl_mods+=("${mod} ${ver}")
        # The §3.3 sentence in the note below rests on no covered SOURCE file carrying Exhibit B.
        # Checked here rather than asserted, so a dependency that adds it stops the regenerate —
        # through the one door at the top of this file, which `notices_test.go` drives directly.
        refuse_if_exhibit_b "${mod}" "$dir"
      fi
      break
    fi
  done
  [ "$found" = 1 ] || emit "_(no license file found in module; see ${mod})_"
  # Apache-2.0 NOTICE files must be carried verbatim (Apache-2.0 §4(d)).
  if [ -f "$dir/NOTICE" ]; then
    emit ""
    emit "NOTICE:"
    emit '```'
    cat "$dir/NOTICE" >>"$tmp"
    emit '```'
  fi
  emit ""
  emit "---"
  emit ""
done <<<"$mods"

# --- Vendored web assets (web/vendor/) and fonts (internal/pdfops/fonts/) ----
# Hand-authored attribution for the third-party code/fonts Nib vendors directly
# (these have no Go module dir to read a LICENSE from). Apache-2.0 deps point to
# the full text already reproduced in the pdfcpu/golang.org/x sections above;
# BSD/ISC/OFL deps reproduce their own text+copyright here, since those are not
# otherwise present in this file. Every vendored library's version is read from a
# VERSION file in its vendor directory (like pdf.js) — updating that file when
# re-vendoring is what keeps these notices honest, and the freshness test
# (notices_test.go) then catches a regenerate that was forgotten.
if [ -f web/vendor/pdfjs/VERSION ]; then
  pdfjs_ver="$(cat web/vendor/pdfjs/VERSION)"
  emit "## Mozilla pdf.js ${pdfjs_ver}"
  emit ""
  emit "Vendored under \`web/vendor/pdfjs/\`. Copyright the Mozilla Foundation and"
  emit "contributors, licensed under the Apache License, Version 2.0. The full"
  emit "license text is reproduced in the \`golang.org/x\`/pdfcpu sections above and"
  emit "at <http://www.apache.org/licenses/LICENSE-2.0>. Upstream:"
  emit "<https://github.com/mozilla/pdf.js>."
  emit ""
  emit "---"
  emit ""
fi

# The CMap tables ship inside the pdf.js package but are NOT Mozilla's and NOT
# Apache-2.0: they are Adobe's, under a three-clause BSD licence with its own
# no-endorsement clause. Attributing them under the pdf.js heading above would
# name the wrong copyright holder and the wrong licence for 1.7 MB of the tree.
if [ -d web/vendor/pdfjs/cmaps ]; then
  emit "## Adobe CMap resources"
  emit ""
  emit "Vendored under \`web/vendor/pdfjs/cmaps/\` (the \`.bcmap\` character-map tables"
  emit "distributed with pdf.js, required to read documents that name a predefined"
  emit "Adobe CMap encoding). Copyright 1990-2009 Adobe Systems Incorporated. All"
  emit "rights reserved. Redistributed under the following three-clause BSD licence,"
  emit "reproduced from \`web/vendor/pdfjs/cmaps/LICENSE\`:"
  emit ""
  # Stripped of the PostScript \`%%Copyright:\` prefix each line carries upstream —
  # the licence text is what must be preserved, and the prefix is an artefact of the
  # format the file is embedded in.
  sed -e 's/^%%Copyright: \{0,1\}//' web/vendor/pdfjs/cmaps/LICENSE | sed -e 's/[[:space:]]*$//' >>"$tmp"
  emit ""
  emit "Upstream: <https://github.com/adobe-type-tools/cmap-resources>."
  emit ""
  emit "---"
  emit ""
fi

# The one class of licence in the walk that is not permissive gets its obligations stated, and
# the modules it covers are the walk's own list (see `mpl_mods` above) — never a hand-typed one.
# The earlier form of this note said the DHT was "reached only from tests" long after
# `internal/rendezvous` linked it into the shipped binary.
#
# The statement is of the licence's TERMS, which are fixed text; it makes no claim about how a
# particular release discharges §3.2, because that is a fact about the release and not about
# this file.
emit "## Note on the Mozilla Public License 2.0 dependencies"
emit ""
if [ "${#mpl_mods[@]}" -eq 0 ]; then
  emit "No module linked into \`./cmd/nib\` is under the Mozilla Public License 2.0."
else
  emit "These modules are linked into the shipped \`nib\` binary and are under the **Mozilla"
  emit "Public License 2.0** (MPL-2.0), a file-level copyleft licence rather than a permissive"
  emit "one. Its full text is reproduced in each module's section above."
  emit ""
  for m in "${mpl_mods[@]}"; do
    emit "- \`${m% *}\` ${m#* }"
  done
  emit ""
  emit "What MPL-2.0 requires of a distribution that includes them:"
  emit ""
  emit "- **The covered files stay under MPL-2.0.** The licence applies file by file. Nib"
  emit "  distributes these modules unmodified; any modification to one of their files would"
  emit "  itself be MPL-2.0 and would have to be made available in source form (§3.1)."
  emit "- **Executable form carries source availability (§3.2).** Whoever distributes a binary"
  emit "  containing them must make the Source Code Form of the covered files available and"
  emit "  tell recipients how to obtain it, at no more than the cost of distribution. The exact"
  emit "  versions are the ones listed above; their source is published at each module's"
  emit "  upstream repository and on the Go module proxy under those versions."
  emit "- **The notices are preserved (§3.4).** Recipients may not be denied the licence text or"
  emit "  the covered files' notices, which is part of what this file is for."
  emit "- **Combination with the AGPLv3 (§3.3).** Nib is a Larger Work under §3.3. MPL-2.0"
  emit "  names the GNU AGPL v3.0 as a Secondary License, so, because none of these files"
  emit "  carries the Exhibit B \"Incompatible With Secondary Licenses\" notice, the covered"
  emit "  files may additionally be distributed under the AGPLv3 as part of Nib, while remaining"
  emit "  available under MPL-2.0 to any recipient who prefers it."
fi
emit ""
emit "---"
emit ""

jsdiff_ver="$(cat web/vendor/diff/VERSION)"
tesseract_ver="$(cat web/vendor/tesseract/VERSION)"
pixelmatch_ver="$(cat web/vendor/pixelmatch/VERSION)"
sed -e "s/@JSDIFF_VER@/${jsdiff_ver}/" \
    -e "s/@TESSERACT_VER@/${tesseract_ver}/" \
    -e "s/@PIXELMATCH_VER@/${pixelmatch_ver}/" >>"$tmp" <<'VENDORED_EOF'
