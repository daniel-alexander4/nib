#!/usr/bin/env bash
# Regenerate THIRD-PARTY-NOTICES.md — the attribution file Nib must ship to
# satisfy the BSD/MIT/Apache-2.0 notice-preservation terms of its dependencies
# (all GPLv3-compatible; see the file's preamble). Run this whenever go.mod or
# the vendored pdf.js changes, and commit the result alongside.
#
# It attributes exactly the third-party code that ends up in a shipped Nib:
#   - the Go modules actually linked into ./cmd/nib (not the full module graph),
#   - the vendored pdf.js engine under web/,
#   - the Go standard library / toolchain.
set -euo pipefail
cd "$(dirname "$0")/.."

OUT="THIRD-PARTY-NOTICES.md"
tmp="$(mktemp)"

emit() { printf '%s\n' "$1" >>"$tmp"; }

emit "# Third-Party Notices"
emit ""
emit "Nib is licensed under the GNU General Public License v3.0 (see \`LICENSE\`)."
emit "It also incorporates the third-party software listed below. Each is under a"
emit "permissive license (BSD, MIT, or Apache-2.0) that is compatible with the"
emit "GPLv3, and each requires that its copyright and license notice be preserved"
emit "in redistributions — that is the purpose of this file."
emit ""
emit "This file is generated by \`build/gen-notices.sh\`; do not edit by hand."
emit ""
emit "---"
emit ""

# --- Go modules linked into the binary -------------------------------------
mods="$(go list -deps -f '{{with .Module}}{{.Path}}{{end}}' ./cmd/nib | grep -v '^$' | sort -u | grep -v '^nib$')"

while IFS= read -r mod; do
  read -r ver dir < <(go list -m -f '{{.Version}} {{.Dir}}' "$mod")
  emit "## ${mod} ${ver}"
  emit ""
  found=0
  for name in LICENSE LICENSE.txt LICENSE.md COPYING COPYING.txt; do
    if [ -f "$dir/$name" ]; then
      emit '```'
      cat "$dir/$name" >>"$tmp"
      emit '```'
      found=1
      break
    fi
  done
  [ "$found" = 1 ] || emit "_(no license file found in module; see ${mod})_"
  # Apache-2.0 NOTICE files must be carried verbatim (Apache-2.0 §4(d)).
  if [ -f "$dir/NOTICE" ]; then
    emit ""
    emit "NOTICE:"
    emit '```'
    cat "$dir/NOTICE" >>"$tmp"
    emit '```'
  fi
  emit ""
  emit "---"
  emit ""
done <<<"$mods"

# --- Vendored pdf.js -------------------------------------------------------
if [ -f web/vendor/pdfjs/VERSION ]; then
  pdfjs_ver="$(cat web/vendor/pdfjs/VERSION)"
  emit "## Mozilla pdf.js ${pdfjs_ver}"
  emit ""
  emit "Vendored under \`web/vendor/pdfjs/\`. Copyright the Mozilla Foundation and"
  emit "contributors, licensed under the Apache License, Version 2.0. The full"
  emit "license text is reproduced in the \`golang.org/x\`/pdfcpu sections above and"
  emit "at <http://www.apache.org/licenses/LICENSE-2.0>. Upstream:"
  emit "<https://github.com/mozilla/pdf.js>."
  emit ""
  emit "---"
  emit ""
fi

# --- Go standard library / toolchain ---------------------------------------
emit "## The Go Programming Language (standard library & toolchain)"
emit ""
emit "Nib is built with the Go toolchain and links the Go standard library,"
emit "Copyright (c) 2009 The Go Authors, licensed under a BSD-3-Clause license:"
emit ""
goroot="$(go env GOROOT)"
if [ -f "$goroot/LICENSE" ]; then
  emit '```'
  cat "$goroot/LICENSE" >>"$tmp"
  emit '```'
fi
emit ""

mv "$tmp" "$OUT"
echo "wrote $OUT ($(wc -l <"$OUT") lines, $(grep -c '^## ' "$OUT") components)"
